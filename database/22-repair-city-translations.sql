insert into public.city_translations (
  city_id,
  locale,
  name
)
select
  cities.id,
  'ro',
  city_source.name
from city_source
join public.cities as cities
  on cities.slug = city_source.slug
left join public.city_translations as existing
  on existing.city_id = cities.id
 and existing.locale = 'ro'
where existing.id is null
on conflict (city_id, locale)
do nothing;


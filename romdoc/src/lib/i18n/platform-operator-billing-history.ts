export type PlatformOperatorBillingHistoryCopy =
  (typeof messages)[keyof typeof messages];

export function getPlatformOperatorBillingHistory(
  locale: AppLocale
): PlatformOperatorBillingHistoryCopy {
  return messages[locale] ?? messages.ro;
}

export function interpolatePlatformBillingHistory(
  template: string,
  values: Record<string, string | number>
) {
  return Object.entries(values).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    template
  );
}
